package tech.codingzen.resultkit.ksp

import com.google.devtools.ksp.isAbstract
import com.google.devtools.ksp.processing.*
import com.google.devtools.ksp.symbol.*
import com.google.devtools.ksp.validate
import java.io.OutputStream

/**
 * KSP processor that generates traced decorator wrappers for interfaces annotated with
 * `@TraceContext`.
 *
 * For each annotated interface, generates a class `{InterfaceName}{suffix}` that:
 * - Delegates all methods to a constructor-injected instance of the interface
 * - For every Res-returning method: wraps the delegated call with `.context(messageλ, locationλ)`
 * - For non-Res methods: plain delegation with no wrapping
 *
 * Both the message lambda and location lambda are `() ->` (zero-argument), so the Kotlin
 * compiler inlines them — on the Ok path no string concatenation or SourceLocation allocation
 * occurs.
 */
internal class TraceContextProcessor(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger,
) : SymbolProcessor {

    override fun process(resolver: Resolver): List<KSAnnotated> {
        val annotated = resolver.getSymbolsWithAnnotation(
            "tech.codingzen.resultkit.context.TraceContext"
        )
        val deferred = mutableListOf<KSAnnotated>()

        for (symbol in annotated) {
            if (!symbol.validate()) {
                deferred.add(symbol)
                continue
            }
            if (symbol !is KSClassDeclaration || symbol.classKind != ClassKind.INTERFACE) {
                logger.error("@TraceContext can only be applied to interfaces", symbol)
                continue
            }
            generateWrapper(symbol)
        }

        return deferred
    }

    private fun generateWrapper(iface: KSClassDeclaration) {
        val suffix = iface.annotations
            .first { it.shortName.asString() == "TraceContext" }
            .arguments
            .firstOrNull { it.name?.asString() == "suffix" }
            ?.value as? String ?: "Traced"

        val ifaceName = iface.simpleName.asString()
        val wrapperName = "$ifaceName$suffix"
        val packageName = iface.packageName.asString()
        val qualifiedIfaceName = iface.qualifiedName?.asString() ?: if (packageName.isEmpty()) ifaceName else "$packageName.$ifaceName"

        val ifaceTypeParams = iface.typeParameters
        val ifaceRendered = ifaceTypeParams.map { renderTypeParam(it) }
        val ifaceTypeParamClause = if (ifaceRendered.isEmpty()) "" else
            "<${ifaceRendered.joinToString(", ") { it.declaration }}>"
        val ifaceWhereClauses = ifaceRendered.flatMap { it.whereClauses }
        val ifaceWhereClause = if (ifaceWhereClauses.isEmpty()) "" else " where ${ifaceWhereClauses.joinToString(", ")}"
        val ifaceTypeArgClause = if (ifaceTypeParams.isEmpty()) "" else
            "<${ifaceTypeParams.joinToString(", ") { it.name.asString() }}>"

        val file = codeGenerator.createNewFile(
            dependencies = Dependencies(aggregating = true, iface.containingFile!!),
            packageName = packageName,
            fileName = wrapperName,
        )

        file.use { out ->
            out.writeln("// Generated by result-kit KSP from $qualifiedIfaceName — do not edit")
            if (packageName.isNotEmpty()) {
                out.writeln("package $packageName")
                out.writeln()
            }
            out.writeln("import tech.codingzen.resultkit.Res")
            out.writeln("import tech.codingzen.resultkit.context.SourceLocation")
            out.writeln("import tech.codingzen.resultkit.context.context")
            out.writeln()
            out.writeln("public class $wrapperName$ifaceTypeParamClause(")
            out.writeln("    private val delegate: $qualifiedIfaceName$ifaceTypeArgClause,")
            out.writeln(") : $qualifiedIfaceName$ifaceTypeArgClause$ifaceWhereClause {")
            out.writeln()

            for (fn in iface.getAllFunctions()) {
                if (isAnyMethod(fn)) continue
                generateMethod(out, iface, fn)
                out.writeln()
            }

            for (prop in iface.getAllProperties()) {
                if (!prop.isAbstract()) continue
                generateProperty(out, prop)
                out.writeln()
            }

            out.writeln("}")
        }
    }

    private data class TypeParamRender(
        val declaration: String,
        val whereClauses: List<String>,
    )

    private fun renderTypeParam(tp: KSTypeParameter): TypeParamRender {
        val name = tp.name.asString()
        val variance = when (tp.variance) {
            Variance.COVARIANT -> "out "
            Variance.CONTRAVARIANT -> "in "
            else -> ""
        }
        val bounds = tp.bounds.toList().filterNot { it.isImplicitAnyBound() }
        return when {
            bounds.isEmpty() -> TypeParamRender("$variance$name", emptyList())
            bounds.size == 1 -> TypeParamRender("$variance$name : ${bounds[0].resolve().toTypeName()}", emptyList())
            else -> {
                val first = "$variance$name : ${bounds[0].resolve().toTypeName()}"
                val rest = bounds.drop(1).map { "$name : ${it.resolve().toTypeName()}" }
                TypeParamRender(first, rest)
            }
        }
    }

    private fun isAnyMethod(fn: KSFunctionDeclaration): Boolean {
        val name = fn.simpleName.asString()
        val returnQn = fn.returnType?.resolve()?.declaration?.qualifiedName?.asString()
        return when (name) {
            "equals" -> {
                if (fn.parameters.size != 1) return false
                val paramType = fn.parameters[0].type.resolve()
                paramType.declaration.qualifiedName?.asString() == "kotlin.Any" &&
                    paramType.isMarkedNullable &&
                    returnQn == "kotlin.Boolean"
            }
            "hashCode" -> fn.parameters.isEmpty() && returnQn == "kotlin.Int"
            "toString" -> fn.parameters.isEmpty() && returnQn == "kotlin.String"
            else -> false
        }
    }

    private fun generateProperty(out: OutputStream, prop: KSPropertyDeclaration) {
        val name = prop.simpleName.asString()
        val type = prop.type.resolve().toTypeName()
        val isVar = prop.isMutable
        val keyword = if (isVar) "var" else "val"
        out.writeln("    override $keyword $name: $type")
        out.writeln("        get() = delegate.$name")
        if (isVar) {
            out.writeln("        set(value) { delegate.$name = value }")
        }
    }

    private fun generateMethod(
        out: OutputStream,
        iface: KSClassDeclaration,
        fn: KSFunctionDeclaration,
    ) {
        val fnName = fn.simpleName.asString()
        val isResReturning = fn.returnType?.resolve()?.isResType() == true
        val isSuspend = fn.modifiers.contains(Modifier.SUSPEND)

        // Build type parameter clause
        val rendered = fn.typeParameters.map { renderTypeParam(it) }
        val typeParamClause = if (rendered.isEmpty()) "" else
            "<${rendered.joinToString(", ") { it.declaration }}>"
        val whereClauses = rendered.flatMap { it.whereClauses }
        val whereClause = if (whereClauses.isEmpty()) "" else " where ${whereClauses.joinToString(", ")}"

        // Build parameter list
        val params = fn.parameters.joinToString(", ") { param ->
            val paramName = param.name?.asString() ?: "_"
            val resolvedType = param.type.resolve()
            val paramType = if (param.isVararg) varargElementType(resolvedType) else resolvedType.toTypeName()
            val varargMod = if (param.isVararg) "vararg " else ""
            "$varargMod$paramName: $paramType"
        }

        // Build argument list for delegate call
        val args = fn.parameters.joinToString(", ") { param ->
            val name = param.name?.asString() ?: "_"
            if (param.isVararg) "*$name" else name
        }

        // Return type
        val returnType = fn.returnType?.resolve()?.toTypeName() ?: "Unit"

        // Signature
        val suspendMod = if (isSuspend) "suspend " else ""
        out.writeln("    override ${suspendMod}fun $typeParamClause$fnName($params): $returnType$whereClause {")

        if (!isResReturning) {
            out.writeln("        return delegate.$fnName($args)")
        } else {
            // Build context message
            val ifaceName = iface.simpleName.asString()
            val contextMsg = buildContextMessage(fn, ifaceName)

            // Source location from KSP declaration.
            // Derive a package-relative path (e.g. "com/example/Repo.kt") so the location
            // is unambiguous in mono-repos with identically-named files in different modules.
            // If KSP can't resolve a FileLocation (synthetic/binary/Java sources), omit the
            // location lambda entirely rather than emitting a misleading line=0.
            val fileLocation = fn.location as? FileLocation

            out.writeln("        return delegate.$fnName($args)")
            if (fileLocation != null) {
                val packagePath = iface.packageName.asString().replace('.', '/')
                val absPath = fileLocation.filePath
                val relPath = if (packagePath.isNotEmpty()) {
                    val relIdx = absPath.indexOf("/$packagePath/")
                    if (relIdx >= 0) absPath.substring(relIdx + 1) else absPath.substringAfterLast('/')
                } else {
                    absPath.substringAfterLast('/')
                }
                out.writeln("            .context(")
                out.writeln("                { $contextMsg },")
                out.writeln("                { SourceLocation(\"$relPath\", ${fileLocation.lineNumber}, \"$fnName\") },")
                out.writeln("            )")
            } else {
                out.writeln("            .context { $contextMsg }")
            }
        }

        out.writeln("    }")
    }

    private fun buildContextMessage(fn: KSFunctionDeclaration, ifaceName: String): String {
        val fnName = fn.simpleName.asString()

        // Check for @TraceMessage override
        val traceMessage = fn.annotations
            .firstOrNull { it.shortName.asString() == "TraceMessage" }
            ?.arguments
            ?.firstOrNull { it.name?.asString() == "value" }
            ?.value as? String

        if (traceMessage != null) {
            // Validate {paramName} references against the actual parameter list before
            // emitting interpolations — an unknown reference would otherwise surface as
            // an "unresolved variable" error in the consumer's compile, not the processor's.
            val paramNames = fn.parameters.mapNotNullTo(mutableSetOf()) { it.name?.asString() }
            val invalidRefs = Regex("\\{(\\w+)\\}").findAll(traceMessage)
                .map { it.groupValues[1] }
                .filterNot { it in paramNames }
                .toList()
            if (invalidRefs.isNotEmpty()) {
                logger.error(
                    "@TraceMessage references undefined parameter(s): ${invalidRefs.joinToString(", ")}",
                    fn,
                )
                return "\"\""
            }

            // Escape characters that would break the generated string literal. `$` must be
            // escaped before {param} interpolation rewrites — the rewrite step deliberately
            // re-emits `$paramName`, and any literal `$` from the user's text would otherwise
            // be interpreted as a Kotlin string interpolation in the generated source.
            val escaped = traceMessage
                .replace("\\", "\\\\")
                .replace("\"", "\\\"")
                .replace("$", "\\$")
            val interpolated = escaped.replace(Regex("\\{(\\w+)\\}")) { match ->
                "\$${match.groupValues[1]}"
            }
            return "\"$interpolated\""
        }

        // Auto-generate: "ClassName.method(p1, p2=$p2, p3)"
        // Values are omitted by default; opt in per-parameter with @TraceInclude.
        val paramParts = fn.parameters.joinToString(", ") { param ->
            val name = param.name?.asString() ?: "_"
            val includeValue = param.annotations.any { it.shortName.asString() == "TraceInclude" }
            if (includeValue) "$name=\$$name" else name
        }
        return "\"$ifaceName.$fnName($paramParts)\""
    }

    /**
     * Returns the element type name for a vararg parameter's array type.
     *
     * KSP gives the array type (e.g. `IntArray` for `vararg ids: Int`). For reference
     * arrays (`Array<T>`) the element type is extracted from the first type argument.
     * For primitive arrays (`IntArray`, `LongArray`, etc.) a direct mapping is used.
     */
    private fun varargElementType(arrayType: KSType): String {
        // Reference arrays: Array<T> — extract T from type argument
        val fromArgs = arrayType.arguments.firstOrNull()?.type?.resolve()?.toTypeName()
        if (fromArgs != null) return fromArgs
        // Primitive arrays: map to element type
        return when (arrayType.declaration.qualifiedName?.asString()) {
            "kotlin.IntArray" -> "kotlin.Int"
            "kotlin.LongArray" -> "kotlin.Long"
            "kotlin.ShortArray" -> "kotlin.Short"
            "kotlin.ByteArray" -> "kotlin.Byte"
            "kotlin.FloatArray" -> "kotlin.Float"
            "kotlin.DoubleArray" -> "kotlin.Double"
            "kotlin.CharArray" -> "kotlin.Char"
            "kotlin.BooleanArray" -> "kotlin.Boolean"
            else -> arrayType.toTypeName()
        }
    }

    /** Returns true for the implicit `kotlin.Any?` upper bound KSP adds to unbounded type params. */
    private fun KSTypeReference.isImplicitAnyBound(): Boolean {
        val resolved = resolve()
        return resolved.declaration.qualifiedName?.asString() == "kotlin.Any" && resolved.isMarkedNullable
    }

    private fun KSType.isResType(): Boolean {
        val name = declaration.qualifiedName?.asString() ?: return false
        return name == "tech.codingzen.resultkit.Res"
    }

    private fun KSType.toTypeName(): String {
        val baseName = when (val decl = declaration) {
            is KSClassDeclaration -> decl.qualifiedName?.asString() ?: decl.simpleName.asString()
            is KSTypeParameter -> decl.name.asString()
            else -> declaration.simpleName.asString()
        }
        val args = if (arguments.isNotEmpty()) {
            "<${arguments.joinToString(", ") { arg ->
                when (arg.variance) {
                    Variance.STAR -> "*"
                    Variance.COVARIANT -> "out ${arg.type?.resolve()?.toTypeName() ?: "*"}"
                    Variance.CONTRAVARIANT -> "in ${arg.type?.resolve()?.toTypeName() ?: "*"}"
                    else -> arg.type?.resolve()?.toTypeName() ?: "*"
                }
            }}>"
        } else ""
        val nullable = if (isMarkedNullable) "?" else ""
        return "$baseName$args$nullable"
    }

    private fun OutputStream.writeln(line: String = "") {
        write("$line\n".toByteArray())
    }
}

/** Registers [TraceContextProcessor] with KSP. */
public class TraceContextProcessorProvider : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor =
        TraceContextProcessor(environment.codeGenerator, environment.logger)
}
